"""Blame the source files of one project by lines, at the pinned commit.

For each file that the project has in TOM, run three line blames on the
pinned clone:
  plain   git blame              (limit 1,800 s for each file)
  w       git blame -w           (limit 1,800 s for each file)
  wmc     git blame -w -M -C     (limit 600 s for each file)
Each blame has its own limit. A blame over its limit stops; the file keeps the
other blames. The line texts come from the blob at the pinned commit, so a file
keeps its rows also when the plain blame stops.

Outputs in the work folder of the project:
  blame.tsv.gz    one row per line: file, line, the commit of each blame ('' if the
                  blame did not end), the origin file of the wmc blame, a blank flag
  files.tsv       one row per file: lines, generated flag, the state of each blame
  limits.tsv      one row per file and blame over a limit (blame 'cap': cut by the run cap)
  errors.tsv      one row per file and blame that failed for another reason
  blame-meta.tsv  counts and seconds
The outputs hold paths and commit ids only (no person data). Read-only on the clone.

    nice -n 19 python3 -I blame_lines.py --project tio__tio --jobs 4
    nice -n 19 python3 -I blame_lines.py --project P --repo R.git --tom P-dataset.parquet \
        --work-dir work/P [--commit SHA] --jobs 4
"""
import argparse
import concurrent.futures as cf
import gzip
import re
import subprocess
import sys
import threading
import time
from pathlib import Path

SCRATCH = Path("/path/to/pilot-scratch")
HERE = Path(__file__).resolve().parent.parent
VARIANTS = {"plain": [], "w": ["-w"], "wmc": ["-w", "-M", "-C"]}
LIMITS = {"plain": 1800.0, "w": 1800.0, "wmc": 600.0}

GEN_PATH = re.compile(
    r"(^|/)(generated|gen-src|autogen|auto_generated|__generated__)(/|$)"
    r"|\.pb\.(cc|h|go|rs)$|_pb2\.|\.g\.(cs|dart)$|[._]generated\.|\.designer\.cs$"
    r"|(^|/)(bindings?|ffi)\.rs$", re.I)
GEN_HEAD = re.compile(
    rb"auto-?generated|code generated|generated by|do not edit|"
    rb"this file (is|was|has been) (auto(matically)?[- ])?generated|"
    rb"automatically generated|@generated", re.I)
SHA = re.compile(rb"^[0-9a-f]{40} \d+ \d+")


class Runner:
    """Runs git processes; abort() kills the live ones and refuses new ones."""

    def __init__(self):
        self.live = set()
        self.lock = threading.Lock()
        self.aborted = threading.Event()

    def run(self, cmd, timeout):
        """Return ('ok', stdout), ('limit', None), ('cut', None) or ('error', text)."""
        with self.lock:
            if self.aborted.is_set():
                return "cut", None
            p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            self.live.add(p)
        try:
            out, err = p.communicate(timeout=timeout)
        except subprocess.TimeoutExpired:
            p.kill()
            p.communicate()
            return ("cut" if self.aborted.is_set() else "limit"), None
        finally:
            with self.lock:
                self.live.discard(p)
        if self.aborted.is_set() and p.returncode != 0:
            return "cut", None
        if p.returncode != 0:
            return "error", err.decode("utf-8", "replace").strip().replace("\n", " ")[:200]
        return "ok", out

    def abort(self):
        with self.lock:
            self.aborted.set()
            for p in list(self.live):
                try:
                    p.kill()
                except OSError:
                    pass


def parse_porcelain(out):
    """Return (shas, origin files) per final line."""
    shas, files = [], []
    cur, cur_file = None, None
    for ln in out.split(b"\n"):
        if ln.startswith(b"\t"):
            shas.append(cur)
            files.append(cur_file)
        elif SHA.match(ln):
            cur = ln[:40].decode()
        elif ln.startswith(b"filename "):
            cur_file = ln[9:].decode("utf-8", "replace")
    return shas, files


def split_lines(data):
    """The lines of a blob as git blame counts them."""
    if not data:
        return []
    lines = data.split(b"\n")
    if data.endswith(b"\n"):
        lines.pop()
    return lines


def one_file(runner, repo, commit, path, limits=None):
    """Blame one file with the 3 blames. Return a dict with rows, file row, limits, errors, seconds."""
    limits = limits or LIMITS
    res = {"path": path, "rows": None, "limits": [], "errors": [], "secs": {}, "state": {}}
    st, data = runner.run(["git", "-C", str(repo), "cat-file", "blob", f"{commit}:{path}"], 600)
    if st != "ok":
        if st == "cut":
            res["limits"].append((path, "cap", 0.0, 0.0))
        else:
            res["errors"].append((path, "blob", str(data)[:200]))
        return res
    texts = split_lines(data)
    n = len(texts)
    got = {}
    for name, opts in VARIANTS.items():
        cmd = ["git", "-C", str(repo), "blame", *opts, "--porcelain", commit, "--", path]
        t0 = time.time()
        st, out = runner.run(cmd, limits[name])
        t = time.time() - t0
        res["secs"][name] = t
        res["state"][name] = st
        if st == "ok":
            shas, files = parse_porcelain(out)
            if len(shas) != n:
                res["errors"].append((path, name, f"line count {len(shas)} is not {n}"))
                res["state"][name] = "error"
            else:
                got[name] = (shas, files)
        elif st in ("limit", "cut"):
            res["limits"].append((path, name if st == "limit" else "cap", limits[name], round(t, 1)))
        else:
            res["errors"].append((path, name, out))
    head = b"\n".join(texts[:40])
    gen = "path" if GEN_PATH.search(path) else ("header" if GEN_HEAD.search(head) else "")
    p, w, m = got.get("plain"), got.get("w"), got.get("wmc")
    rows = []
    for i in range(n):
        rows.append((path, i + 1, p[0][i] if p else "", w[0][i] if w else "",
                     m[0][i] if m else "", (m[1][i] or "") if m else "",
                     1 if texts[i].strip() == b"" else 0))
    res["rows"] = rows
    res["file"] = (path, n, gen, res["state"]["plain"], res["state"]["w"], res["state"]["wmc"])
    return res


def clean(x):
    return str(x).replace("\t", " ").replace("\n", " ").replace("\r", " ")


class ProjectBlame:
    """Collects the file results of one project into its output files."""

    def __init__(self, project, repo, commit, work):
        self.p, self.repo, self.commit, self.work = project, repo, commit, Path(work)
        self.work.mkdir(parents=True, exist_ok=True)
        self.lock = threading.Lock()
        self.fb = gzip.open(self.work / "blame.tsv.gz.part", "wt", compresslevel=3)
        self.fb.write("file_path\tline\tsha_plain\tsha_w\tsha_wmc\torig_file_wmc\tblank\n")
        self.ff = open(self.work / "files.tsv.part", "w")
        self.ff.write("file_path\tn_lines\tgenerated\tplain\tw\twmc\n")
        self.limits, self.errors = [], []
        self.tot = {k: 0.0 for k in VARIANTS}
        self.files = 0
        self.t0 = time.time()

    def add(self, res):
        with self.lock:
            self.files += 1
            for k, v in res["secs"].items():
                self.tot[k] += v
            self.limits.extend(res["limits"])
            self.errors.extend(res["errors"])
            if res["rows"] is None:
                return
            for r in res["rows"]:
                self.fb.write("\t".join(clean(x) for x in r) + "\n")
            self.ff.write("\t".join(clean(x) for x in res["file"]) + "\n")

    def finish(self, n_files):
        self.fb.close()
        self.ff.close()
        (self.work / "blame.tsv.gz.part").rename(self.work / "blame.tsv.gz")
        (self.work / "files.tsv.part").rename(self.work / "files.tsv")
        with open(self.work / "limits.tsv", "w") as f:
            f.write("project\tfile_path\tblame\tlimit_s\tseconds\n")
            for path, b, lim, s in sorted(self.limits, key=lambda x: (x[0], x[1])):
                f.write(f"{self.p}\t{clean(path)}\t{b}\t{lim:g}\t{s:g}\n")
        with open(self.work / "errors.tsv", "w") as f:
            f.write("project\tfile_path\tblame\tmessage\n")
            for path, b, msg in sorted(self.errors, key=lambda x: (x[0], x[1])):
                f.write(f"{self.p}\t{clean(path)}\t{b}\t{clean(msg)}\n")
        wall = time.time() - self.t0
        nl = {b: sum(1 for x in self.limits if x[1] == b) for b in ("plain", "w", "wmc", "cap")}
        with open(self.work / "blame-meta.tsv", "w") as fm:
            fm.write("project\tcommit\tfiles\tfiles_done\terrors\tlimit_plain\tlimit_w\tlimit_wmc\tcut_cap\t"
                     "wall_s\tplain_s\tw_s\twmc_s\n")
            fm.write(f"{self.p}\t{self.commit}\t{n_files}\t{self.files}\t{len(self.errors)}\t{nl['plain']}\t"
                     f"{nl['w']}\t{nl['wmc']}\t{nl['cap']}\t{wall:.1f}\t{self.tot['plain']:.1f}\t"
                     f"{self.tot['w']:.1f}\t{self.tot['wmc']:.1f}\n")
        return {"files": n_files, "errors": len(self.errors), **{f"limit_{k}": v for k, v in nl.items()},
                "wall_s": wall, "cpu_s": sum(self.tot.values())}


def tom_files(tom):
    """The TOM file set, the largest files (by TOM rows) first."""
    import duckdb
    con = duckdb.connect()
    return [r[0] for r in con.execute(
        "SELECT file_path FROM read_parquet(?) GROUP BY 1 ORDER BY count(*) DESC, 1", [str(tom)]).fetchall()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    ap.add_argument("--repo")
    ap.add_argument("--tom")
    ap.add_argument("--work-dir")
    ap.add_argument("--commit")
    ap.add_argument("--jobs", type=int, default=4)
    a = ap.parse_args()
    p = a.project
    repo = Path(a.repo) if a.repo else SCRATCH / "out-local" / p / f"{p}-original.git"
    tom = Path(a.tom) if a.tom else SCRATCH / "hf-tom" / "parquet" / f"{p}-dataset.parquet"
    out = Path(a.work_dir) if a.work_dir else HERE / "work" / p
    commit = a.commit or subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"],
                                        capture_output=True, text=True, check=True).stdout.strip()
    files = tom_files(tom)
    runner = Runner()
    pb = ProjectBlame(p, repo, commit, out)
    with cf.ThreadPoolExecutor(a.jobs) as ex:
        for fu in cf.as_completed([ex.submit(one_file, runner, repo, commit, f) for f in files]):
            pb.add(fu.result())
    s = pb.finish(len(files))
    for e in pb.errors[:20]:
        print("ERROR", p, *e, file=sys.stderr)
    print(f"{p}: {s['files']} files, {s['errors']} errors, limits plain {s['limit_plain']} w {s['limit_w']} "
          f"wmc {s['limit_wmc']}, {s['wall_s']:.0f} s wall", file=sys.stderr)


if __name__ == "__main__":
    main()
