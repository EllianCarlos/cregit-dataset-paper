"""Blame the source files of one project by lines, at the pinned commit.

For each file that the project has in TOM, run three line blames on the
original (pinned) clone:
  plain   git blame
  w       git blame -w
  wmc     git blame -w -M -C
and write one row per line: file, line, the commit of each blame, the origin
file of the wmc blame, and a blank-line flag. Also write a file table with a
generated-file flag. Read-only on the clone.

    nice -n 19 python3 -I blame_lines.py --project tio__tio --jobs 4
"""
import argparse
import concurrent.futures as cf
import gzip
import re
import subprocess
import sys
import time
from pathlib import Path

import duckdb

SCRATCH = Path("/path/to/pilot-scratch")
HERE = Path(__file__).resolve().parent.parent
VARIANTS = {"plain": [], "w": ["-w"], "wmc": ["-w", "-M", "-C"]}
TIMEOUT = 900

GEN_PATH = re.compile(
    r"(^|/)(generated|gen-src|autogen|auto_generated|__generated__)(/|$)"
    r"|\.pb\.(cc|h|go|rs)$|_pb2\.|\.g\.(cs|dart)$|[._]generated\.|\.designer\.cs$"
    r"|(^|/)(bindings?|ffi)\.rs$", re.I)
GEN_HEAD = re.compile(
    rb"auto-?generated|code generated|generated by|do not edit|"
    rb"this file (is|was|has been) (auto(matically)?[- ])?generated|"
    rb"automatically generated|@generated", re.I)
SHA = re.compile(rb"^[0-9a-f]{40} \d+ \d+")


def parse_porcelain(out):
    """Return a list of (sha, origin_file) per final line, and the contents."""
    shas, files, texts = [], [], []
    cur, cur_file = None, None
    for ln in out.split(b"\n"):
        if ln.startswith(b"\t"):
            shas.append(cur)
            files.append(cur_file)
            texts.append(ln[1:])
        elif SHA.match(ln):
            cur = ln[:40].decode()
        elif ln.startswith(b"filename "):
            cur_file = ln[9:].decode("utf-8", "replace")
    return shas, files, texts


def blame(repo, commit, path, opts):
    cmd = ["git", "-C", str(repo), "blame", *opts, "--porcelain", commit, "--", path]
    r = subprocess.run(cmd, capture_output=True, timeout=TIMEOUT)
    if r.returncode != 0:
        raise RuntimeError(r.stderr.decode("utf-8", "replace")[:200])
    return parse_porcelain(r.stdout)


def one_file(repo, commit, path):
    res, cpu = {}, {}
    for name, opts in VARIANTS.items():
        t0 = time.time()
        try:
            res[name] = blame(repo, commit, path, opts)
        except subprocess.TimeoutExpired:
            res[name] = None
        cpu[name] = time.time() - t0
    base = res["plain"]
    if base is None:
        return path, None, None, cpu
    texts = base[2]
    head = b"\n".join(texts[:40])
    gen = "path" if GEN_PATH.search(path) else ("header" if GEN_HEAD.search(head) else "")
    rows = []
    n = len(texts)
    for i in range(n):
        w = res["w"]
        m = res["wmc"]
        rows.append((path, i + 1, base[0][i],
                     w[0][i] if w and len(w[0]) == n else "",
                     m[0][i] if m and len(m[0]) == n else "",
                     m[1][i] if m and len(m[1]) == n else "",
                     1 if texts[i].strip() == b"" else 0))
    return path, rows, (path, n, gen), cpu


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    ap.add_argument("--jobs", type=int, default=4)
    a = ap.parse_args()
    p = a.project
    repo = SCRATCH / "out-local" / p / f"{p}-original.git"
    tom = SCRATCH / "hf-tom" / "parquet" / f"{p}-dataset.parquet"
    out = HERE / "work" / p
    out.mkdir(parents=True, exist_ok=True)
    commit = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"],
                            capture_output=True, text=True, check=True).stdout.strip()
    con = duckdb.connect()
    files = [r[0] for r in con.execute(
        "SELECT DISTINCT file_path FROM read_parquet(?) ORDER BY 1", [str(tom)]).fetchall()]
    t0 = time.time()
    tot = {k: 0.0 for k in VARIANTS}
    errors = []
    with gzip.open(out / "blame.tsv.gz", "wt") as fb, open(out / "files.tsv", "w") as ff:
        fb.write("file_path\tline\tsha_plain\tsha_w\tsha_wmc\torig_file_wmc\tblank\n")
        ff.write("file_path\tn_lines\tgenerated\n")
        with cf.ThreadPoolExecutor(a.jobs) as ex:
            futs = [ex.submit(one_file, repo, commit, f) for f in files]
            for fu in cf.as_completed(futs):
                try:
                    path, rows, frow, cpu = fu.result()
                except Exception as e:  # noqa: BLE001
                    errors.append(str(e))
                    continue
                for k, v in cpu.items():
                    tot[k] += v
                if rows is None:
                    errors.append(f"timeout {path}")
                    continue
                for r in rows:
                    fb.write("\t".join(str(x).replace("\t", " ").replace("\n", " ") for x in r) + "\n")
                ff.write(f"{frow[0]}\t{frow[1]}\t{frow[2]}\n")
    wall = time.time() - t0
    with open(out / "blame-meta.tsv", "w") as fm:
        fm.write("project\tcommit\tfiles\terrors\twall_s\tplain_s\tw_s\twmc_s\n")
        fm.write(f"{p}\t{commit}\t{len(files)}\t{len(errors)}\t{wall:.1f}\t"
                 f"{tot['plain']:.1f}\t{tot['w']:.1f}\t{tot['wmc']:.1f}\n")
    for e in errors[:20]:
        print("ERROR", p, e, file=sys.stderr)
    print(f"{p}: {len(files)} files, {len(errors)} errors, {wall:.0f} s wall", file=sys.stderr)


if __name__ == "__main__":
    main()
